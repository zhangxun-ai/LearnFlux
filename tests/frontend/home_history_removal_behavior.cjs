const assert = require('node:assert/strict');
const { APIManager, TaskHistoryManager, UIManager } = require('../../src/web/static/js/app.js');
const memory = new Map();
global.localStorage = { getItem: key => memory.get(key) || null, setItem: (key, value) => memory.set(key, value) };
global.document = { querySelectorAll: () => [] };
global.setTimeout = () => {};
TaskHistoryManager.renderHistory = () => {};
TaskHistoryManager.syncFromServer = async () => true;
const statuses = [];
UIManager.showStatus = (...args) => statuses.push(args);
const records = [{id:'one', title:'Repeated'}, {id:'two', title:'Repeated'}];
const reset = () => memory.set('vta_task_history', JSON.stringify(records));
(async () => {
    reset(); let requests = 0;
    global.window = { LearnFluxHistoryConfirm: { open: async () => false } };
    APIManager.removeHistoryTasks = async () => { requests++; };
    await TaskHistoryManager.deleteTask('one');
    assert.equal(requests, 0);
    assert.equal(TaskHistoryManager.getHistory().length, 2);
    global.window.LearnFluxHistoryConfirm.open = async () => true;
    let finish;
    APIManager.removeHistoryTasks = ids => {
        requests++;
        assert.deepEqual(ids, ['one']);
        return new Promise(resolve => { finish = resolve; });
    };
    const pending = TaskHistoryManager.deleteTask('one');
    await TaskHistoryManager.deleteTask('one');
    assert.equal(requests, 1, 'Repeated clicks must not send duplicate writes');
    assert.equal(TaskHistoryManager.getHistory().length, 2, 'Keep the record until persistence succeeds');
    finish({code:200}); await pending;
    assert.deepEqual(TaskHistoryManager.getHistory().map(task => task.id), ['two']);
    assert.ok(memory.get('learnflux_history_changed'));
    reset();
    APIManager.removeHistoryTasks = async () => { throw new Error('Temporary failure'); };
    const originalError = console.error; console.error = () => {};
    await TaskHistoryManager.deleteTask('one'); console.error = originalError;
    assert.equal(TaskHistoryManager.getHistory().length, 2);
    assert.equal(statuses.at(-1)[0], 'error');
    console.log('Home history removal behavior checks passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
